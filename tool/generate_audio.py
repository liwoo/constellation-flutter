def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'assets', 'audio'))
    parser.add_argument('--only', nargs='*', help='Only render these file names')
    args = parser.parse_args()
    out_dir = os.path.abspath(args.out)
    os.makedirs(out_dir, exist_ok=True)

    for tool in ('sox', 'lame'):
        if shutil.which(tool) is None:
            raise SystemExit(f'{tool} not found on PATH (brew install sox lame)')

    with tempfile.TemporaryDirectory() as tmp:
        for name, fn in SFX.items():
            if args.only and name not in args.only:
                continue
            if name.endswith('.mp3'):
                # Longer, non-latency-critical sounds ship as MP3 to keep the
                # web bundle small. Short reactive sounds stay WAV (no decoder
                # delay).
                wav = os.path.join(tmp, 'sfx.wav')
                write_wav(wav, fn(tmp))
                subprocess.run(['lame', '--quiet', '-b', '128', '-q', '2', wav,
                                os.path.join(out_dir, name)], check=True)
            else:
                write_wav(os.path.join(out_dir, name), fn(tmp))
            print('wrote', name)

        if not args.only or 'music_ambient.mp3' in args.only:
            music, loop_dur = music_loop(tmp)
            wav = os.path.join(tmp, 'music.wav')
            write_wav(wav, music, peak_db=-2)
            subprocess.run(['lame', '--quiet', '-b', '112', '-q', '2', wav,
                            os.path.join(out_dir, 'music_ambient.mp3')], check=True)
            print(f'wrote music_ambient.mp3 (loop {loop_dur:.6f}s, preroll {MUSIC_PREROLL_S}s)')


if __name__ == '__main__':
    main()
