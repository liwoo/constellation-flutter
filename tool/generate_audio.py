def brass_chord(freqs, dur, attack=0.03):
    out = np.zeros(n_samples(dur))
    for f in freqs:
        for h in range(1, 9):
            out += (1 / h ** 1.3) * osc(f * h * (1 + RNG.uniform(-0.002, 0.002)), dur)
    return out * adsr(dur, attack, 0.2, 0.6, dur * 0.5) / len(freqs)


