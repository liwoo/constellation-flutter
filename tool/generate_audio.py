def music_loop(tmp):
    """Soothing ambient loop: warm pads, soft sub, sparse celesta melody.

    Rendered so that it loops seamlessly: anything ringing past the loop end
    is wrapped to the start, and the reverb is applied to two back-to-back
    copies (keeping the second) so its tail also wraps. The exported file is
    [last PREROLL seconds] + loop + [first PREROLL seconds] so that loop
    points stay seamless even if a decoder adds/strips MP3 encoder delay.
    """
    beat = 60 / MUSIC_BPM
    bar = 4 * beat
    loop_n = n_samples(MUSIC_BARS * bar)
    loop_dur = loop_n / SR
    tail_s = 6.0
    buf = np.zeros((loop_n + n_samples(tail_s), 2))

    def add(start_s, sig, pan=0.0):
        i = n_samples(max(0.0, start_s))
        left = np.cos((pan + 1) * np.pi / 4) * np.sqrt(2)
        right = np.sin((pan + 1) * np.pi / 4) * np.sqrt(2)
        end = min(i + len(sig), len(buf))
        buf[i:end, 0] += sig[: end - i] * left
        buf[i:end, 1] += sig[: end - i] * right

    # D major-ish dreamy progression, 2 bars per chord.
    chords = [
        ('D3', ['D4', 'F#4', 'A4', 'C#5', 'E5']),   # Dmaj9
        ('B2', ['D4', 'F#4', 'A4', 'C#5', 'E5']),   # Bm11-ish
        ('G2', ['D4', 'F#4', 'B4', 'C#5', 'E5']),   # Gmaj9#11
        ('A2', ['C#4', 'E4', 'A4', 'B4', 'E5']),    # Aadd9
        ('D3', ['C#4', 'F#4', 'A4', 'D5', 'E5']),   # Dmaj9 (voicing 2)
        ('F#2', ['C#4', 'E4', 'A4', 'C#5', 'F#5']), # F#m7
        ('G2', ['D4', 'F#4', 'A4', 'B4', 'D5']),    # Gmaj9
        ('G2', ['D4', 'E4', 'Bb4', 'D5', 'G5']),    # Gm6 - wistful borrowed chord
    ]

    def pad_voice(freq, dur):
        out = np.zeros(n_samples(dur))
        for det in (-0.004, 0.0, 0.0045):
            for h, amp in ((1, 1.0), (2, 0.32), (3, 0.12), (4, 0.06), (5, 0.025)):
                out += amp * osc(freq * h * (1 + det), dur, phase=RNG.uniform(0, 2 * np.pi))
        t = times(dur)
        breath = 1 + 0.12 * np.sin(2 * np.pi * t / (dur * 0.9) + RNG.uniform(0, 6.28))
        return out * breath * adsr(dur, 1.6, 0.5, 0.85, 2.2) / 3

    chord_dur = 2 * bar
    for ci, (root, tones) in enumerate(chords):
        st = ci * chord_dur
        d = chord_dur + 2.4  # overlap into the next chord for smooth crossfades
        for k, n in enumerate(tones):
            add(st, pad_voice(note(n), d) * 0.075, pan=-0.6 + 1.2 * k / (len(tones) - 1))
        sub = osc(note(root), d) * adsr(d, 1.2, 0.5, 0.9, 2.0) * 0.22
        sub += osc(note(root) * 2, d) * adsr(d, 1.5, 0.5, 0.8, 2.0) * 0.05
        add(st, sub)

    # Sparse celesta melody on D major pentatonic. (beat_offset, note, velocity)
    motif_a = [(0, 'F#5', 0.8), (1.5, 'A5', 0.6), (2.5, 'B5', 0.55), (4, 'A5', 0.7), (6, 'E5', 0.5)]
    motif_b = [(0, 'D6', 0.6), (1, 'B5', 0.5), (2.5, 'A5', 0.6), (4, 'F#5', 0.7), (5.5, 'E5', 0.45), (6.5, 'D5', 0.5)]
    motif_c = [(0, 'A5', 0.7), (2, 'F#5', 0.5), (3, 'E5', 0.5), (4.5, 'D5', 0.6)]
    motif_d = [(0, 'B5', 0.6), (1, 'D6', 0.55), (2, 'E6', 0.6), (4, 'D6', 0.5), (5, 'A5', 0.45), (6, 'B5', 0.4)]
    melody_plan = [motif_a, None, motif_b, None, motif_c, motif_a, motif_d, None]
    for ci, motif in enumerate(melody_plan):
        if motif is None:
            continue
        for b_off, n, vel in motif:
            st = ci * chord_dur + b_off * beat + RNG.uniform(-0.01, 0.01)
            add(st, celesta(note(n), 2.6, decay_scale=1.6) * vel * 0.11, pan=RNG.uniform(-0.35, 0.35))

    # Faint twinkling stars
    star_notes = ['A6', 'D7', 'E7', 'F#7', 'B6']
    for _ in range(22):
        st = RNG.uniform(0, loop_dur)
        add(st, bell(note(star_notes[int(RNG.integers(0, 5))]), 1.5, 0.8) * 0.018, pan=RNG.uniform(-0.9, 0.9))

    # Wrap anything ringing past the end back to the start.
    loop = buf[:loop_n].copy()
    loop[: len(buf) - loop_n] += buf[loop_n:]

    # Gentle tone shaping + reverb on two copies so the tail wraps too.
    doubled = np.concatenate([loop, loop])
    src = os.path.join(tmp, 'music_dry.wav')
    wet = os.path.join(tmp, 'music_wet.wav')
    write_wav(src, doubled, peak_db=-6)
    sox(src, wet, 'lowpass', '5200', 'reverb', '70', '60', '100', '100', '20', '-3')
    processed = read_wav(wet)[loop_n: 2 * loop_n]

    pre = n_samples(MUSIC_PREROLL_S)
    with_rolls = np.concatenate([processed[-pre:], processed, processed[:pre]])
    # Fade in only the very first preroll (it is never part of the loop region).
    with_rolls[:pre] *= np.linspace(0, 1, pre)[:, None]
    return with_rolls, loop_dur


