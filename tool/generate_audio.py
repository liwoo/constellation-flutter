#!/usr/bin/env python3
"""Procedurally synthesizes every sound effect and the background music loop.

All audio in assets/audio/ is generated by this script, so there are no
third-party licensing concerns and every sound can be re-tuned in code.

Requirements: python3 + numpy, plus `sox` and `lame` on PATH
(macOS: `brew install sox lame`).

Usage:
    python3 tool/generate_audio.py            # writes into assets/audio/
    python3 tool/generate_audio.py --out DIR
"""

