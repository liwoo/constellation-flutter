def write_wav(path, x, peak_db=-3.0):
    x = np.asarray(x, dtype=np.float64)
    peak = np.max(np.abs(x)) or 1.0
    x = x / peak * (10 ** (peak_db / 20))
    pcm = np.clip(x * 32767, -32768, 32767).astype('<i2')
    with wave.open(path, 'wb') as w:
        w.setnchannels(2 if x.ndim == 2 else 1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def read_wav(path):
    with wave.open(path, 'rb') as w:
        ch = w.getnchannels()
        data = np.frombuffer(w.readframes(w.getnframes()), dtype='<i2').astype(np.float64) / 32768
    return data.reshape(-1, ch) if ch == 2 else data


def sox(inp, out, *effects):
    subprocess.run(['sox', inp, out, *effects], check=True)


def with_reverb(x, reverberance=40, room=60, wet_db=-6, tail=0.6, stereo_out=None, tmp=None):
    """Adds a reverb tail with sox. Keeps channel count unless stereo_out=True."""
    src = os.path.join(tmp, 'rv_in.wav')
    dst = os.path.join(tmp, 'rv_out.wav')
    write_wav(src, x, peak_db=-6)
    fx = []
    if stereo_out and x.ndim == 1:
        fx += ['channels', '2']
    fx += ['pad', '0', str(tail), 'reverb', str(reverberance), '50', str(room), '100', '0', str(wet_db)]
    sox(src, dst, *fx)
    return read_wav(dst)


