MUSIC_BARS = 16
MUSIC_PREROLL_S = 2.0


# ---------------------------------------------------------------------------
# Primitives
# ---------------------------------------------------------------------------

def n_samples(dur):
    return int(round(dur * SR))


def times(dur):
    return np.arange(n_samples(dur)) / SR


def note(name_or_midi):
    """MIDI number -> Hz. Accepts ints or names like 'C6', 'F#4'."""
    if isinstance(name_or_midi, str):
        names = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
        s = name_or_midi
        semi = names[s[0]]
        i = 1
        while i < len(s) and s[i] in '#b':
            semi += 1 if s[i] == '#' else -1
            i += 1
        octave = int(s[i:])
        midi = 12 * (octave + 1) + semi
    else:
        midi = name_or_midi
    return 440.0 * 2 ** ((midi - 69) / 12)


def osc(freq, dur, phase=0.0):
    """Sine oscillator; `freq` may be a scalar or a per-sample array."""
    n = n_samples(dur)
    f = np.broadcast_to(np.asarray(freq, dtype=np.float64), (n,))
    ph = 2 * np.pi * np.cumsum(f) / SR + phase
    return np.sin(ph)


def exp_env(dur, decay, attack=0.002):
    t = times(dur)
    env = np.exp(-t / decay)
    if attack > 0:
        a = np.clip(t / attack, 0, 1)
        env *= a * a * (3 - 2 * a)  # smoothstep attack - no clicks
    return env


def adsr(dur, a, d, s, r):
    t = times(dur)
    env = np.ones_like(t) * s
    env[t < a] = t[t < a] / a
    dmask = (t >= a) & (t < a + d)
    env[dmask] = 1 - (1 - s) * (t[dmask] - a) / d
    rel_start = dur - r
    rmask = t >= rel_start
    env[rmask] *= np.clip(1 - (t[rmask] - rel_start) / r, 0, 1)
    return env


def partials(freq, dur, spec, attack=0.002):
    """Additive tone. spec = [(ratio, amp, decay_seconds), ...]."""
    out = np.zeros(n_samples(dur))
    for ratio, amp, decay in spec:
        f = freq * ratio
        if f > SR * 0.45:
            continue
        out += amp * osc(f, dur, phase=RNG.uniform(0, 2 * np.pi)) * exp_env(dur, decay, attack)
    return out


MUSIC_BOX = [(1, 1.0, 0.55), (2, 0.35, 0.25), (3, 0.12, 0.15), (4.16, 0.10, 0.08)]
GLASS_BELL = [(1, 1.0, 0.9), (2.76, 0.45, 0.35), (5.40, 0.22, 0.18), (8.93, 0.10, 0.09)]
CELESTA = [(1, 1.0, 0.7), (2, 0.25, 0.3), (4, 0.10, 0.12), (6.8, 0.04, 0.05)]


def musicbox(freq, dur=1.2, decay_scale=1.0):
    spec = [(r, a, d * decay_scale) for r, a, d in MUSIC_BOX]
    return partials(freq, dur, spec)


def bell(freq, dur=1.6, decay_scale=1.0):
    spec = [(r, a, d * decay_scale) for r, a, d in GLASS_BELL]
    return partials(freq, dur, spec)


def celesta(freq, dur=1.4, decay_scale=1.0):
    spec = [(r, a, d * decay_scale) for r, a, d in CELESTA]
    return partials(freq, dur, spec, attack=0.004)


def noise(dur):
    return RNG.uniform(-1, 1, n_samples(dur))


def highpass_diff(x):
    return np.diff(x, prepend=0.0)


def lowpass(x, cutoff):
    """Simple one-pole low-pass (vectorized via exponential smoothing loop)."""
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y


def mix(length_s, *events, stereo=False):
    """events: (start_seconds, signal[, pan]) -> mono or stereo buffer."""
    n = n_samples(length_s)
    out = np.zeros((n, 2)) if stereo else np.zeros(n)
    for ev in events:
        start, sig = ev[0], ev[1]
        pan = ev[2] if len(ev) > 2 else 0.0
        i = n_samples(start)
        if i >= n:
            continue
        seg = sig[: n - i]
        if stereo:
            left = np.cos((pan + 1) * np.pi / 4)
            right = np.sin((pan + 1) * np.pi / 4)
            out[i:i + len(seg), 0] += seg * left * np.sqrt(2)
            out[i:i + len(seg), 1] += seg * right * np.sqrt(2)
        else:
            out[i:i + len(seg)] += seg
    return out


def fade_tail(x, dur=0.02):
    n = min(n_samples(dur), len(x))
    ramp = np.linspace(1, 0, n)
    if x.ndim == 2:
        x[-n:] *= ramp[:, None]
    else:
        x[-n:] *= ramp
    return x


