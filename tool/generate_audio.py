def sfx_magnet_snap():
    """Short magnetic 'clack' with a bright metallic ping (pitched per letter)."""
    dur = 0.32
    pull = osc(np.linspace(500, 1400, n_samples(0.018)), 0.018) * np.linspace(0, 1, n_samples(0.018)) ** 2 * 0.12
    click = highpass_diff(noise(0.012)) * exp_env(0.012, 0.0015, attack=0.0) * 0.55
    f_thunk = 150 + 110 * np.exp(-times(0.09) / 0.012)
    thunk = osc(f_thunk, 0.09) * exp_env(0.09, 0.03, attack=0.0008) * 0.75
    ping = partials(note('C6'), 0.3, [(1, 0.55, 0.11), (2.0, 0.22, 0.06), (2.92, 0.16, 0.035), (4.1, 0.08, 0.02)], attack=0.0008)
    x = mix(dur, (0.0, pull), (0.018, click), (0.018, thunk), (0.018, ping))
    return fade_tail(x)


def sfx_connect_fail():
    """Friendly 'bu-bum' nope: two soft low notes falling, with a muted thud."""
    def soft_tone(f, dur, decay):
        f_arr = f * (1 - 0.06 * times(dur) / dur)
        tone = (osc(f_arr, dur) + osc(f_arr * 3, dur) / 9 + osc(f_arr * 5, dur) / 25)
        return tone * exp_env(dur, decay, attack=0.004)
    thud = lowpass(noise(0.06), 400) * exp_env(0.06, 0.015) * 2.5
    x = mix(0.34, (0.0, soft_tone(311, 0.09, 0.05)), (0.0, thud), (0.09, soft_tone(233, 0.22, 0.08)))
    return fade_tail(x)


