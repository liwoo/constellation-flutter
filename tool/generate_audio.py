def sfx_bubbles_rise(tmp):
    """A flurry of bubbles bubbling up - pitch climbs as they rise."""
    events = []
    count = 18
    starts = np.sort(RNG.uniform(0, 1.0, count) ** 1.3)  # denser at the start
    for k, st in enumerate(starts):
        progress = k / (count - 1)
        f0 = 320 + 900 * progress + RNG.uniform(-60, 60)
        d = RNG.uniform(0.045, 0.085)
        tt = times(d)
        f = f0 * (1 + 2.2 * (tt / d) ** 1.4)  # classic bubble 'bloop' upward chirp
        b = osc(f, d) * exp_env(d, d * 0.45, attack=0.003)
        amp = RNG.uniform(0.45, 0.9) * (0.6 + 0.4 * (1 - progress))
        events.append((st, b * amp, RNG.uniform(-0.7, 0.7)))
    x = mix(1.25, *events, stereo=True)
    x = with_reverb(x, reverberance=25, room=40, wet_db=-8, tail=0.3, tmp=tmp)
    return fade_tail(x, 0.05)


